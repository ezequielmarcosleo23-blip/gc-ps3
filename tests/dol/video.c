/* ---- registros de la VI (0xCC002000, de 16 bits) ------------------------------ */

#ifdef GCPS3_HOST
static uint32_t xfb[XFB_BYTES / 4];
uint32_t *video_xfb(void) { return xfb; }
void video_init_480i(void) {}
void video_wait_frame(void) {}
void video_flush(void) {}
#else
#define VI16(off) (*(volatile uint16_t *)(0xCC002000u + (off)))

enum {
    VTR = 0x00, DCR = 0x02, HTR0 = 0x04, HTR1 = 0x08, VTO = 0x0C, VTE = 0x10, BBOI = 0x14,
    BBEI = 0x18, TFBL = 0x1C, BFBL = 0x24, DPV = 0x2C, DI0 = 0x30, DI1 = 0x34, DI2 = 0x38,
    DI3 = 0x3C, HSW = 0x48, HSR = 0x4A, CLOCK = 0x6C, FBWIDTH = 0x70,
};

static void vi32(uint32_t off, uint32_t v)
{
    VI16(off) = (uint16_t)(v >> 16);
    VI16(off + 2) = (uint16_t)v;
}

uint32_t *video_xfb(void) { return (uint32_t *)(0x80000000u | XFB_PHYS); }

void video_init_480i(void)
{
    VI16(DCR) = 0x0002;                          /* reset: borra las interrupciones */
    VI16(DCR) = 0x0000;
    VI16(VTR) = 0x0F06;                          /* ACV 240 líneas por campo, EQU 6 */
    vi32(HTR0, 0x476901ADu);                     /* HCS 71, HCE 105, HLW 429 */
    vi32(HTR1, 0x02EA5140u);                     /* HBS 373, HBE 162, HSY 64 */
    vi32(VTO, 0x00030018u);                      /* campo impar: PSB 3, PRB 24 */
    vi32(VTE, 0x00020019u);                      /* campo par: PSB 2, PRB 25 */
    vi32(BBOI, 0x410C410Cu);
    vi32(BBEI, 0x40ED40EDu);
    vi32(TFBL, 0x10000000u | (XFB_PHYS >> 5));   /* POFF: dirección en bloques de 32 */
    vi32(BFBL, 0x10000000u | ((XFB_PHYS + XFB_WIDTH * 2) >> 5));
    VI16(HSW) = (uint16_t)((XFB_WIDTH / 16) << 8 | (XFB_WIDTH * 2 / 16)); /* WPL 40, STD 80 */
    VI16(HSR) = 0;                               /* sin escalado horizontal */
    VI16(FBWIDTH) = (uint16_t)XFB_WIDTH;
    vi32(DI0, 0x110701AEu);                      /* línea 263, segunda mitad: campo par */
    vi32(DI1, 0x10010001u);                      /* línea 1: campo impar */
    vi32(DI2, 0);
    vi32(DI3, 0);
    VI16(CLOCK) = 0;                             /* 27 MHz */
    VI16(DCR) = 0x0001;                          /* ENB, entrelazado, NTSC */
}

void video_wait_frame(void)
{
    while (VI16(DPV) < 264)                      /* hasta el campo par */
        ;
    while (VI16(DPV) >= 263)                     /* hasta la línea 1 del cuadro siguiente */
        ;
}

void video_flush(void)
{
    const uint32_t start = 0x80000000u | XFB_PHYS;
    for (uint32_t a = start; a < start + XFB_BYTES; a += 32)
        __asm__ volatile("dcbf 0, %0" : : "r"(a) : "memory");
    __asm__ volatile("sync" : : : "memory");
}
#endif

/* ---- dibujo --------------------------------------------------------------------- */

void video_fill(uint32_t color)
{
    uint32_t *p = video_xfb();
    for (uint32_t i = 0; i < XFB_BYTES / 4; i++)
        p[i] = color;
}

void video_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color)
{
    uint32_t *p = video_xfb();
    if (x >= XFB_PAIRS || y >= XFB_HEIGHT)
        return;
    if (w > XFB_PAIRS - x)
        w = XFB_PAIRS - x;
    if (h > XFB_HEIGHT - y)
        h = XFB_HEIGHT - y;
    for (uint32_t j = 0; j < h; j++)
        for (uint32_t i = 0; i < w; i++)
            p[(y + j) * XFB_PAIRS + x + i] = color;
}

