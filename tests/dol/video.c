uint32_t video_text_pairs(const char *s, uint32_t scale)
{
    uint32_t n = 0;
    while (s[n])
        n++;
    return n * 8 * scale;
}

void video_text(uint32_t x, uint32_t y, uint32_t scale, uint32_t color, const char *s)
{
    for (; *s; s++, x += 8 * scale) {
        const unsigned c = (unsigned char)*s;
        if (c < 32 || c >= 32 + sizeof font / sizeof font[0])
            continue;
        for (uint32_t row = 0; row < 8; row++)
            for (uint32_t col = 0; col < 8; col++)
                if (font[c - 32][row] & (0x80u >> col))
                    video_rect(x + col * scale, y + row * 2 * scale, scale, 2 * scale, color);
    }
}

void video_bars(uint32_t y, uint32_t h)
{
    static const uint32_t bars[8] = {
        0xB480B480u, 0xA12CA18Du, 0x839C832Cu, 0x7049703Au,  /* blanco, amarillo, cian, verde */
        0x54B754C6u, 0x416441D4u, 0x23D42373u, 0x10801080u,  /* magenta, rojo, azul, negro */
    };
    for (uint32_t k = 0; k < 8; k++)
        video_rect(k * (XFB_PAIRS / 8), y, XFB_PAIRS / 8, h, bars[k]);
}

/* ---- CRC-32 ----------------------------------------------------------------------- */

static uint32_t crc_table[256];

uint32_t video_crc32(void)
{
    if (!crc_table[1])
        for (uint32_t n = 0; n < 256; n++) {
            uint32_t c = n;
            for (int k = 0; k < 8; k++)
                c = (c & 1) ? 0xEDB88320u ^ (c >> 1) : c >> 1;
            crc_table[n] = c;
        }
    const uint32_t *p = video_xfb();
    uint32_t crc = 0xFFFFFFFFu;
    for (uint32_t i = 0; i < XFB_BYTES / 4; i++) {
        const uint32_t w = p[i];
        for (int sh = 24; sh >= 0; sh -= 8)      /* Y U Y V, como en la RAM del Gekko */
            crc = crc_table[(crc ^ (w >> sh)) & 0xFFu] ^ (crc >> 8);
    }
    return crc ^ 0xFFFFFFFFu;
}
